// Helper to construct player gameweeks dynamically
function buildGameweeks(
  position: 'FWD' | 'MID' | 'DEF' | 'GK',
  gwConfigs: Array<{
    gameweek: number;
    opponent: string;
    opponentTier: number;
    isHome: boolean;
    scoreResult: string;
    stats: {
      goals: number;
      assists: number;
      keyPasses: number;
      passAccuracyPct: number;
      tackles: number;
      interceptions: number;
      cleanSheet: boolean;
      saves: number;
      errorsLeadToGoal: number;
      minutesPlayed: number;
    };
  }>
) {
  const gws: Player['gameweeks'] = {};
  for (const item of gwConfigs) {
    const { rating, breakdown } = calculateGameweekRating(position, item.stats, item.opponentTier);
    gws[item.gameweek] = {
      gameweek: item.gameweek,
      opponent: item.opponent,
      opponentTier: item.opponentTier,
      isHome: item.isHome,
      scoreResult: item.scoreResult,
      stats: item.stats,
      rating,
      breakdown,
    };
  }
  return gws;
}

