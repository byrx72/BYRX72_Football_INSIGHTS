// Helper to construct player gameweeks dynamically
function buildGameweeks(
  position: 'FWD' | 'MID' | 'DEF' | 'GK',
  baseG: number,
  baseA: number,
  baseKP: number,
  baseAcc: number,
  baseTkl: number,
  baseInt: number,
  baseCS: number,
  baseSv: number,
  opponents: { opp: string; tier: number; home: boolean; score: string }[]
) {
  const gwMap: Record<number, any> = {};

  opponents.forEach((o, idx) => {
    const gw = idx + 1;
    const factor = 0.75 + Math.sin(gw * 1.7) * 0.35;
    const gwGoals = Math.max(0, Math.round((baseG / 8) * factor + (gw % 3 === 0 ? 1 : 0)));
    const gwAssists = Math.max(0, Math.round((baseA / 8) * factor));
    const gwKP = Math.max(1, Math.round((baseKP / 8) * factor));
    const gwAcc = Math.min(98, Math.max(70, Math.round(baseAcc + Math.sin(gw) * 4)));
    const gwTkl = Math.max(0, Math.round((baseTkl / 8) * factor));
    const gwInt = Math.max(0, Math.round((baseInt / 8) * factor));
    const gwCS = baseCS > 0 ? (gw % 2 === 0) : false;
    const gwSaves = position === 'GK' ? Math.max(2, Math.round((baseSv / 8) * (1 + Math.sin(gw) * 0.4))) : 0;

    const stats = {
      goals: gwGoals,
      assists: gwAssists,
      keyPasses: gwKP,
      passAccuracyPct: gwAcc,
      tackles: gwTkl,
      interceptions: gwInt,
      cleanSheet: gwCS,
      saves: gwSaves,
      errorsLeadToGoal: 0,
      minutesPlayed: 90,
    };

    const evaluated = calculateGameweekRating(position, stats, o.tier);

    gwMap[gw] = {
      gameweek: gw,
      opponent: o.opp,
      opponentTier: o.tier,
      isHome: o.home,
      scoreResult: o.score,
      stats,
      rating: evaluated.rating,
      breakdown: evaluated.breakdown,
    };
  });

  return gwMap;
}

